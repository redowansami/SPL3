import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

const ACCENT = [22, 163, 74]; // --accent: #16a34a
const DANGER = [220, 38, 38]; // --danger: #dc2626
const TEXT_DARK = [30, 32, 38];
const TEXT_MUTED = [90, 94, 104];

function truncate(text, max = 600) {
  if (!text) return "";
  const str = String(text);
  return str.length <= max ? str : str.slice(0, max) + "…";
}

function formatDate(value) {
  if (!value) return "—";
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return "—";
  return d.toLocaleString();
}

function formatDuration(startedAt, endedAt) {
  if (!startedAt || !endedAt) return "—";
  const start = new Date(startedAt).getTime();
  const end = new Date(endedAt).getTime();
  if (Number.isNaN(start) || Number.isNaN(end)) return "—";
  const seconds = Math.max(0, (end - start) / 1000);
  if (seconds < 60) return `${seconds.toFixed(1)}s`;
  const minutes = Math.floor(seconds / 60);
  const rest = Math.round(seconds % 60);
  return `${minutes}m ${rest}s`;
}

function addFooter(doc) {
  const pageCount = doc.internal.getNumberOfPages();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pageCount; i += 1) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(...TEXT_MUTED);
    doc.text("Generated by ATLAS-Scan", 40, pageHeight - 24);
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 40, pageHeight - 24, { align: "right" });
  }
}

function addTitleBand(doc, meta) {
  const pageWidth = doc.internal.pageSize.getWidth();
  doc.setFillColor(...ACCENT);
  doc.rect(0, 0, pageWidth, 70, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont(undefined, "bold");
  doc.text("ATLAS-Scan", 40, 30);
  doc.setFontSize(11);
  doc.setFont(undefined, "normal");
  doc.text("Security Scan Report", 40, 48);
  doc.setFontSize(8);
  doc.text(`Generated ${formatDate(new Date())}`, pageWidth - 40, 30, { align: "right" });
  if (meta.runId) {
    doc.text(`Run ID: ${meta.runId}`, pageWidth - 40, 44, { align: "right" });
  }
  return 90;
}

function addMetaTable(doc, startY, meta, result) {
  const engineLabel = meta.engine === "pyrit" ? "PyRIT (multi-turn)" : "Garak";
  const status = result.status ?? (result.ok ? "completed" : "failed");

  autoTable(doc, {
    startY,
    theme: "plain",
    styles: { fontSize: 9, textColor: TEXT_DARK, cellPadding: 3 },
    columnStyles: { 0: { fontStyle: "bold", cellWidth: 110 } },
    body: [
      ["Target URL", meta.targetUrl || "—"],
      ["Attack Engine", engineLabel],
      ["Status", String(status)],
      ["Scan Started", formatDate(meta.startedAt)],
      ["Scan Ended", formatDate(meta.endedAt)],
      ["Duration", formatDuration(meta.startedAt, meta.endedAt)],
    ],
  });

  return doc.lastAutoTable.finalY + 20;
}

function addSummarySection(doc, startY, isPyrit, result) {
  const pageWidth = doc.internal.pageSize.getWidth();
  doc.setFontSize(12);
  doc.setFont(undefined, "bold");
  doc.setTextColor(...TEXT_DARK);
  doc.text("Summary", 40, startY);

  let rows;
  if (isPyrit) {
    rows = [
      ["Turns Executed", String(result.executed_turns ?? 0)],
      ["Objective Achieved", result.achieved ? "Yes" : "No"],
      ["Outcome", result.outcome ?? "—"],
    ];
  } else {
    const attempts = result.attempts_evaluated ?? 0;
    const failures = result.failure_count ?? 0;
    const successes = Math.max(0, attempts - failures);
    rows = [
      ["Attempts Evaluated", String(attempts)],
      ["Failures Found (Successful Exploits)", String(failures)],
      ["Clean Attempts", String(successes)],
    ];
  }

  autoTable(doc, {
    startY: startY + 10,
    theme: "grid",
    styles: { fontSize: 9, cellPadding: 6, halign: "center" },
    headStyles: { fillColor: ACCENT, textColor: 255, fontStyle: "bold" },
    head: [rows.map((r) => r[0])],
    body: [rows.map((r) => r[1])],
    tableWidth: pageWidth - 80,
    margin: { left: 40, right: 40 },
  });

  return doc.lastAutoTable.finalY + 20;
}

function addGarakAttackPath(doc, startY, result) {
  doc.setFontSize(12);
  doc.setFont(undefined, "bold");
  doc.setTextColor(...TEXT_DARK);
  doc.text("Attack Path", 40, startY);

  const paths = result.attack_paths || [];
  if (paths.length === 0) {
    doc.setFontSize(9);
    doc.setFont(undefined, "normal");
    doc.setTextColor(...ACCENT);
    doc.text("No successful attack paths were found for this probe.", 40, startY + 18);
    return startY + 36;
  }

  const body = paths.map((item) => [
    String(item.attempt_seq),
    item.goal || "—",
    item.probe || "—",
    truncate((item.prompt_turns || []).join("\n---\n"), 500),
    truncate(item.output, 500),
    (item.triggers || []).length > 0 ? item.triggers.join(", ") : `detector: ${item.detector}`,
    item.score != null ? item.score.toFixed(2) : "—",
  ]);

  autoTable(doc, {
    startY: startY + 10,
    theme: "striped",
    styles: { fontSize: 8, cellPadding: 4, valign: "top", overflow: "linebreak" },
    headStyles: { fillColor: ACCENT, textColor: 255, fontStyle: "bold" },
    head: [["#", "Goal / Technique", "Probe", "Injected Prompt", "Target Output", "Triggers", "Score"]],
    body,
    columnStyles: {
      0: { cellWidth: 20 },
      1: { cellWidth: 70 },
      2: { cellWidth: 65 },
      3: { cellWidth: 110 },
      4: { cellWidth: 110 },
      5: { cellWidth: 70 },
      6: { cellWidth: 30 },
    },
    margin: { left: 40, right: 40 },
  });

  return doc.lastAutoTable.finalY + 20;
}

function addPyritConversation(doc, startY, result) {
  doc.setFontSize(12);
  doc.setFont(undefined, "bold");
  doc.setTextColor(...TEXT_DARK);
  doc.text("Attack Turns", 40, startY);

  if (result.final_score_rationale) {
    doc.setFontSize(9);
    doc.setFont(undefined, "italic");
    doc.setTextColor(...TEXT_MUTED);
    const rationale = doc.splitTextToSize(`Scorer rationale: ${result.final_score_rationale}`, doc.internal.pageSize.getWidth() - 80);
    doc.text(rationale, 40, startY + 16);
    startY += 16 + rationale.length * 11;
  }

  const turns = result.conversation || [];
  if (turns.length === 0) {
    doc.setFontSize(9);
    doc.setFont(undefined, "normal");
    doc.setTextColor(...ACCENT);
    doc.text("No conversation was recorded.", 40, startY + 18);
    return startY + 36;
  }

  const body = turns.map((t) => [
    String(t.turn),
    t.role === "attacker" ? "Attacker" : "Target",
    truncate(t.text, 900),
  ]);

  autoTable(doc, {
    startY: startY + 10,
    theme: "striped",
    styles: { fontSize: 8, cellPadding: 4, valign: "top", overflow: "linebreak" },
    headStyles: { fillColor: ACCENT, textColor: 255, fontStyle: "bold" },
    head: [["Turn", "Role", "Message"]],
    body,
    columnStyles: {
      0: { cellWidth: 30 },
      1: { cellWidth: 60 },
      2: { cellWidth: 390 },
    },
    margin: { left: 40, right: 40 },
  });

  return doc.lastAutoTable.finalY + 20;
}

function addMitigationsSection(doc, startY, mitigations) {
  doc.setFontSize(12);
  doc.setFont(undefined, "bold");
  doc.setTextColor(...TEXT_DARK);
  doc.text("Required Mitigations", 40, startY);

  if (!mitigations || mitigations.length === 0) {
    doc.setFontSize(9);
    doc.setFont(undefined, "normal");
    doc.setTextColor(...ACCENT);
    doc.text("No mitigations required — no successful exploits were found.", 40, startY + 18);
    return;
  }

  const body = [];
  for (const m of mitigations) {
    const techniques = (m.atlas_techniques || []).map((t) => t.name).join(", ") || "—";
    const strategies = (m.strategies || []).join("; ") || "—";
    const mitigationNames = (m.atlas_mitigations || [])
      .map((mit) => `${mit.name}: ${truncate(mit.description, 300)}`)
      .join("\n\n") || "—";
    body.push([m.label || m.probe || m.objectiveId || "—", techniques, mitigationNames, strategies]);
  }

  autoTable(doc, {
    startY: startY + 10,
    theme: "striped",
    styles: { fontSize: 8, cellPadding: 4, valign: "top", overflow: "linebreak" },
    headStyles: { fillColor: DANGER, textColor: 255, fontStyle: "bold" },
    head: [["Probe / Objective", "ATLAS Techniques", "Mitigations", "Strategies"]],
    body,
    columnStyles: {
      0: { cellWidth: 90 },
      1: { cellWidth: 90 },
      2: { cellWidth: 220 },
      3: { cellWidth: 90 },
    },
    margin: { left: 40, right: 40 },
  });
}

export function generateScanReportPdf({ meta, result, mitigations }) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const isPyrit = "conversation" in result;

  let y = addTitleBand(doc, meta);
  y = addMetaTable(doc, y, meta, result);
  y = addSummarySection(doc, y, isPyrit, result);

  if (y > doc.internal.pageSize.getHeight() - 150) {
    doc.addPage();
    y = 40;
  }

  y = isPyrit ? addPyritConversation(doc, y, result) : addGarakAttackPath(doc, y, result);

  if (y > doc.internal.pageSize.getHeight() - 150) {
    doc.addPage();
    y = 40;
  }

  addMitigationsSection(doc, y, mitigations);
  addFooter(doc);

  return doc;
}
